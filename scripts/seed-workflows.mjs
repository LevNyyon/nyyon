#!/usr/bin/env node
// Emit the SQL that installs the system workflow catalog.
//
// The catalog lives in code (workers/api/src/workflows/seeds/*.js) because a
// workflow IS the product's behaviour, not user data. This script turns it
// into SQL so the same definitions can be applied to a local D1 during setup
// or to a remote one on deploy, with no worker running.
//
//   node scripts/seed-workflows.mjs | wrangler d1 execute <db> --local --file=/dev/stdin
//
// Rows are upserted only where source='system': an operator's edit to a
// workflow (source='nyo') always survives a reinstall, exactly like a
// knowledge doc.

import { readdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const seedsDir = join(here, '..', 'workers', 'api', 'src', 'workflows', 'seeds');

const q = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const files = (await readdir(seedsDir)).filter((f) => f.endsWith('.js')).sort();
const all = [];
for (const f of files) {
  const mod = await import(pathToFileURL(join(seedsDir, f)).href);
  for (const w of mod.workflows || []) all.push(w);
}

const now = Date.now();
const lines = [
  '-- Generated by scripts/seed-workflows.mjs — do not edit by hand.',
  `-- ${all.length} system workflows from ${files.length} family files.`,
  '',
];
for (const w of all) {
  lines.push(
    `INSERT INTO workflows (slug, name, description, trigger, steps, source, status, created_at, updated_at, created_by)`,
    `VALUES (${q(w.slug)}, ${q(w.name)}, ${q(w.description || '')}, ${q(JSON.stringify(w.trigger || { kind: 'on-demand' }))}, ${q(JSON.stringify(w.steps || []))}, 'system', 'active', ${now}, ${now}, 'system')`,
    `ON CONFLICT(slug) DO UPDATE SET name=excluded.name, description=excluded.description,`,
    `  trigger=excluded.trigger, steps=excluded.steps, updated_at=excluded.updated_at`,
    `  WHERE workflows.source = 'system';`,
    '',
  );
}
process.stdout.write(lines.join('\n'));
process.stderr.write(`seeded ${all.length} workflows from ${files.length} files\n`);
